"""日志节流：把"每来一条就打一行"改成"状态变化立刻打 + 每 N 秒提醒一次"。

============================ 为什么需要它 ============================
设备层稳态时每 2 s 一条 INFO（约 10.7 MB/天）；真机失效时每 2 s 一条 ERROR
（再翻一倍）。这些日志对排障有用，但**重复度极高**：真正的信号是"什么时候开始坏、
什么时候恢复"，不是"我又失败了一次"。

节流规则（调用方负责记住上次打印的时刻）：

    last <= 0            → 第一次，必须打（保证故障起点/恢复点可定位）
    now - last >= 间隔   → 打（提醒，避免长时间静默）
    其它                 → 不打

⚠️ 只在"状态没变"时抑制；状态变化（成功↔失败）由调用方自己判断并立即打印。
"""

from __future__ import annotations


def should_emit(last_ts: float, now_ts: float, interval: float) -> bool:
    """是否该打印这一行。`last_ts` 传 0（或负数）表示"从没打过"。"""
    if last_ts <= 0.0:
        return True
    return (now_ts - last_ts) >= interval
